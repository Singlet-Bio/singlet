#!/usr/bin/env python
"""w4_atlas: atlas-wide savings by lever, with bundle-bootstrap CIs on the byte shares.

    python -P tools/w4_atlas_levers.py        -> results/w4_atlas_levers.md

Each lever = (members it acts on) x (saving fraction on those bytes). Shares are byte-weighted ratio estimators over the 180
sampled bundles (95% percentile bootstrap over bundles, 10,000 draws). Saving fractions are either MEASURED HERE (recode
slices), MEASURED IN THE EARLIER STUDY on other data (tagged 'study'), or counted from the central directory (CRC dedup).
The CIs cover bundle sampling only; the saving fractions are point values with no interval (n=1 per category here).
TB columns: share x 3.89 TB (catalog total as given) and share x N*mean (HT: 8,202 x 302.6 MB = 2.48 TB, no catalog needed).
"""
import csv, os, sys, collections
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE); RES = os.path.join(ROOT, "results")
N = 8202; B_CAT = 3.89e12
rng = np.random.default_rng(7)
M = list(csv.DictReader(open(os.path.join(RES, "w4_atlas_members.tsv"), encoding="utf-8"), delimiter="\t"))
Bn = list(csv.DictReader(open(os.path.join(RES, "w4_atlas_bundles.tsv"), encoding="utf-8"), delimiter="\t"))
gi = {b["gse"]: i for i, b in enumerate(Bn)}; n = len(Bn)
btot = np.array([int(b["total"]) for b in Bn], float)
B_HT = N * btot.mean()
BOOT = rng.integers(0, n, size=(10000, n))

def q(cats):
    v = np.zeros(n)
    for r in M:
        if r["category"] in cats: v[gi[r["gse"]]] += int(r["csize"])
    return v

def ci(v):
    est = v.sum() / btot.sum()
    r = v[BOOT].sum(1) / btot[BOOT].sum(1)
    return est, np.percentile(r, 2.5), np.percentile(r, 97.5)

def fmt(x): return f"{100*x:.2f}%"
def tb(x): return f"{x/1e12:.2f}"

quick = {}
qp = os.path.join(RES, "w4_atlas_recode_quick.tsv")
if os.path.exists(qp):
    for r in csv.DictReader(open(qp), delimiter="\t"):
        d6 = float(r["deflate6"]); quick[r["label"]] = dict(zstd=1 - float(r["zstd19"]) / d6, xz=1 - float(r["xz9e"]) / d6)

levers = []   # (name, status, v (bytes saved per bundle), note)
pz_cnt = q({"exon_counts.1pz", "intron_counts.1pz"})
levers.append(("restricted-member removal", "REALIZED: 0 of 34,252 members restricted in the live sample", np.zeros(n), "stale 1/40 index implied ~31% of bytes (parent); live sample shows none left"))
whitelist = q({"star_Solo.out/Gene/raw/barcodes.tsv"})
feat = q({"star_Solo.out/Gene/raw/features.tsv", "star_Solo.out/Gene/filtered/features.tsv"})
vocab = q({"feature_vocab.json"})
levers.append(("names/vocab A: whitelist raw/barcodes.tsv -> chemistry id", "measured: 3 distinct contents in 467 members (CRC), 99.6% of bytes are repeats", whitelist * 0.996, ""))
levers.append(("names/vocab B: raw+filtered features.tsv -> vocab id", "measured: byte-identical raw==filtered in 467/467, 2 distinct contents", feat * 0.997, ""))
levers.append(("names/vocab C: feature_vocab.json once per build", "measured: 4 distinct contents in 180 bundles", vocab * 0.975, "bytes only; also saves one 0.3-0.8 MB fetch per study"))
levers.append(("names/vocab D: names, permutation, ptr, colsums, barcodes inside exon/intron .1pz", "study (Track A, 14 corpus matrices 114.4->53.5 MB = -53.2%), NOT re-measured on atlas members", pz_cnt * 0.532, "out-of-sample for the atlas"))
psi = q({"splice_psi.1pz"})
levers.append(("derived members A: splice_psi.1pz regenerated from sj_counts.1pz", "study (E4): 14/14 files byte-identical, gen-A bundle only", psi, "shipped file holds rounded 0/1, see notes/e4.md"))
pay = pz_cnt * (1 - 0.532) * 0.151
levers.append(("payload recoding: b_rans16 on exon/intron payload", "study: -15.1% byte-weighted on the payload that remains after lever D (0.468 x 0.151 of today's .1pz bytes)", pay, "projection; no single codec implements all levers"))
mtx_raw = q({"star_Solo.out/Gene/raw/matrix.mtx"}); mtx_fil = q({"star_Solo.out/Gene/filtered/matrix.mtx"}); amb = q({"ambient_profile.tsv"})
for lab, key, v in (("raw matrix.mtx", "star_Solo_out__Gene__raw__matrix_mtx__1", mtx_raw), ("filtered matrix.mtx", "star_Solo_out__Gene__filtered__matrix_mtx__1", mtx_fil), ("ambient_profile.tsv", "ambient_profile_tsv__1", amb)):
    if key in quick:
        levers.append((f"legacy-text recoding: {lab} with xz-9e", f"measured here, n=1 member, 6 MB slice: -{100*quick[key]['xz']:.1f}% vs deflate-6 (zstd-19: -{100*quick[key]['zstd']:.1f}%)", v * quick[key]["xz"], "general-purpose codec only, no CSC parse"))
cand = [("CANDIDATE (w4_mtx is testing): filtered/matrix.mtx derivable from raw", mtx_fil), ("CANDIDATE (untested): ambient_profile.tsv derivable from empties counts", amb),
        ("CANDIDATE (untested): gene_expression.tsv derivable from counts + lengths", q({"gene_expression.tsv"}))]
out = ["# w4_atlas savings by lever (generated by tools/w4_atlas_levers.py)", "", "| lever | basis | saved share of live bytes (95% CI) | TB at catalog scale 3.89 TB | TB at HT scale 2.48 TB |", "|---|---|---|---|---|"]
tot = np.zeros(n)
for name, basis, v, note in levers:
    e, lo, hi = ci(v); tot += v
    out.append(f"| {name} | {basis} | {fmt(e)} ({fmt(lo)} to {fmt(hi)}) | {tb(e*B_CAT)} | {tb(e*B_HT)} |")
e, lo, hi = ci(tot)
out.append(f"| **sum of the measured/study levers above (overlaps removed: none overlap)** | | **{fmt(e)} ({fmt(lo)} to {fmt(hi)})** | {tb(e*B_CAT)} | {tb(e*B_HT)} |")
for name, v in cand:
    e, lo, hi = ci(v)
    out.append(f"| {name} | upper bound if fully derivable | {fmt(e)} ({fmt(lo)} to {fmt(hi)}) | {tb(e*B_CAT)} | {tb(e*B_HT)} |")
open(os.path.join(RES, "w4_atlas_levers.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out))
print("HT total", B_HT / 1e12)
