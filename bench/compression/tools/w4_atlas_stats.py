#!/usr/bin/env python
"""w4_atlas step 3: composition, generation, restricted, method, size and duplication tables with bootstrap CIs.

    python -P tools/w4_atlas_stats.py            # writes results/w4_atlas_tables.md (+ prints it)

Estimators. The 180 bundles are a uniform random sample of the N=8,202 public bundles (NOT of bytes). For a quantity q_i
measured on bundle i with size b_i the byte-weighted ratio estimator is  share = sum(q_i)/sum(b_i)  and the atlas total is
share * B with B = 3.89 TB (the catalog total supplied by the parent session). The alternative Horvitz-Thompson
estimate N*mean(q_i) is shown where it matters (it does not use B and is noisier because bundle sizes are heavy tailed).
CIs: 10,000 bootstrap resamples of whole bundles (percentile 95%).
"""
import csv, collections, math, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RES = os.path.join(ROOT, "results")
N_ATLAS = 8202
B_ATLAS = 3.89e12
NBOOT = 10000
rng = np.random.default_rng(20261022)

out_lines = []


def P(s=""):
    out_lines.append(s); print(s)


def rd(name):
    return list(csv.DictReader(open(os.path.join(RES, name), encoding="utf-8"), delimiter="\t"))


M = rd("w4_atlas_members.tsv")
Bn = rd("w4_atlas_bundles.tsv")
gses = [b["gse"] for b in Bn]
gi = {g: i for i, g in enumerate(gses)}
n = len(gses)
btot = np.array([int(b["total"]) for b in Bn], float)
gen = np.array([b["gen"] for b in Bn])


def mat(keyfn, valfn=lambda r: int(r["csize"]), rows=M):
    keys = {}
    d = collections.defaultdict(float)
    for r in rows:
        k = keyfn(r)
        if k is None: continue
        d[(gi[r["gse"]], k)] += valfn(r)
        keys.setdefault(k, len(keys))
    Q = np.zeros((n, len(keys)))
    for (i, k), v in d.items(): Q[i, keys[k]] = v
    return Q, list(keys)


BOOT = rng.integers(0, n, size=(NBOOT, n))


def ratio_ci(q, b=btot, boot=BOOT):
    """byte-weighted ratio sum(q)/sum(b) with 95% bootstrap CI"""
    est = q.sum() / b.sum()
    r = q[boot].sum(1) / b[boot].sum(1)
    return est, np.percentile(r, 2.5), np.percentile(r, 97.5)


def ratio_ci_multi(Q, b=btot, boot=BOOT):
    est = Q.sum(0) / b.sum()
    lo = np.zeros(Q.shape[1]); hi = np.zeros(Q.shape[1])
    for j in range(Q.shape[1]):
        r = Q[boot, j].sum(1) / b[boot].sum(1)
        lo[j], hi[j] = np.percentile(r, [2.5, 97.5])
    return est, lo, hi


def fmt_b(x):
    for u, s in (("TB", 1e12), ("GB", 1e9), ("MB", 1e6), ("kB", 1e3)):
        if abs(x) >= s: return f"{x/s:.2f} {u}"
    return f"{x:.0f} B"


def pct(x): return f"{100*x:.2f}%"


P("# w4_atlas tables (generated by tools/w4_atlas_stats.py)")
P()
P(f"Sample: {n} bundles, {fmt_b(btot.sum())} total, mean {fmt_b(btot.mean())}, median {fmt_b(np.median(btot))}, max {fmt_b(btot.max())}. "
  f"Catalog: N={N_ATLAS}, B={fmt_b(B_ATLAS)}, mean {fmt_b(B_ATLAS/N_ATLAS)}.")
mu = btot.mean(); bm = btot[BOOT].mean(1)
P(f"Sample mean bundle size {fmt_b(mu)} (95% bootstrap CI {fmt_b(np.percentile(bm,2.5))} to {fmt_b(np.percentile(bm,97.5))}); "
  f"catalog mean {fmt_b(B_ATLAS/N_ATLAS)} is {'inside' if np.percentile(bm,2.5) <= B_ATLAS/N_ATLAS <= np.percentile(bm,97.5) else 'OUTSIDE'} that interval.")
P()

# ---------------------------------------------------------------- 1. composition
Qg, kg = mat(lambda r: r["group"])
Qg_ov = (btot - Qg.sum(1))[:, None]
Qg = np.hstack([Qg, Qg_ov]); kg = kg + ["zip local headers + central directory"]
est, lo, hi = ratio_ci_multi(Qg)
order = np.argsort(-est)
P("## T1. Composition by member group (compressed bytes inside the zip)")
P()
P("| group | sample bytes | share of bytes (95% CI) | atlas projection = share x 3.89 TB (95% CI) | atlas HT: N x mean (95% CI) |")
P("|---|---|---|---|---|")
for j in order:
    ht = N_ATLAS * Qg[:, j].mean()
    hts = N_ATLAS * Qg[:, j][BOOT].mean(1)
    P(f"| {kg[j]} | {fmt_b(Qg[:,j].sum())} | {pct(est[j])} ({pct(lo[j])} to {pct(hi[j])}) | {fmt_b(est[j]*B_ATLAS)} ({fmt_b(lo[j]*B_ATLAS)} to {fmt_b(hi[j]*B_ATLAS)}) | {fmt_b(ht)} ({fmt_b(np.percentile(hts,2.5))} to {fmt_b(np.percentile(hts,97.5))}) |")
P()

Qc, kc = mat(lambda r: r["category"])
Qc = np.hstack([Qc, (btot - Qc.sum(1))[:, None]]); kc = kc + ["(zip overhead)"]
est_c, lo_c, hi_c = ratio_ci_multi(Qc)
cnt = collections.Counter(r["category"] for r in M)
usz = collections.Counter(); csz = collections.Counter(); meth = collections.defaultdict(collections.Counter)
for r in M:
    usz[r["category"]] += int(r["usize"]); csz[r["category"]] += int(r["csize"]); meth[r["category"]][r["method"]] += 1
P("## T1b. Composition by member category (all 50 distinct member names; sample-level members shown without samples/<GSM>/)")
P()
P("| member | # members | in-zip bytes | share (95% CI) | atlas projection (95% CI) | uncompressed bytes | ratio unc/zip | zip method (count) |")
P("|---|---|---|---|---|---|---|---|")
for j in np.argsort(-est_c):
    k = kc[j]
    if k == "(zip overhead)":
        P(f"| {k} | | {fmt_b(Qc[:,j].sum())} | {pct(est_c[j])} ({pct(lo_c[j])} to {pct(hi_c[j])}) | {fmt_b(est_c[j]*B_ATLAS)} | | | |")
        continue
    ms = ", ".join(f"{ {'0':'STORED','8':'DEFLATE'}.get(m, 'method'+m)}:{c}" for m, c in sorted(meth[k].items()))
    P(f"| {k} | {cnt[k]} | {fmt_b(Qc[:,j].sum())} | {pct(est_c[j])} ({pct(lo_c[j])} to {pct(hi_c[j])}) | {fmt_b(est_c[j]*B_ATLAS)} ({fmt_b(lo_c[j]*B_ATLAS)} to {fmt_b(hi_c[j]*B_ATLAS)}) | {fmt_b(usz[k])} | {usz[k]/max(csz[k],1):.2f} | {ms} |")
P()

# ---------------------------------------------------------------- 1b. generations
P("## T2. Bundle generations (rule: gen B = every sample carries text/STARsolo members, i.e. ambient_profile.tsv / gene_expression.tsv / cell_qc_metrics.tsv / star_SJ.out.tab / star_Solo.out/*; gen A = none of them)")
P()
is_b = (gen == "B").astype(float)
for lab, mask in (("A (.1pz members + small json/tsv)", gen == "A"), ("B (.1pz + text/STARsolo + donor/ + mt/ tables)", gen == "B")):
    qb = btot * mask
    e, l, h = ratio_ci(qb)
    qn, ln, hn = ratio_ci(mask.astype(float), b=np.ones(n))
    P(f"- gen {lab}: {int(mask.sum())} bundles = {pct(qn)} of bundles ({pct(ln)} to {pct(hn)}); {fmt_b(qb.sum())} = {pct(e)} of bytes ({pct(l)} to {pct(h)}); "
      f"mean bundle {fmt_b(btot[mask].mean())}, median {fmt_b(np.median(btot[mask]))}, max {fmt_b(btot[mask].max())}")
P()
P("Within-generation composition (share of that generation's bytes):")
P()
P("| group | gen A | gen B |")
P("|---|---|---|")
rows_ = []
for j, k in enumerate(kg):
    ea = ratio_ci(Qg[gen == "A", j], b=btot[gen == "A"], boot=rng.integers(0, int((gen == "A").sum()), size=(NBOOT, int((gen == "A").sum()))))
    eb = ratio_ci(Qg[gen == "B", j], b=btot[gen == "B"], boot=rng.integers(0, int((gen == "B").sum()), size=(NBOOT, int((gen == "B").sum()))))
    rows_.append((eb[0], f"| {k} | {pct(ea[0])} ({pct(ea[1])} to {pct(ea[2])}) | {pct(eb[0])} ({pct(eb[1])} to {pct(eb[2])}) |"))
for _, s in sorted(rows_, reverse=True): P(s)
P()

# Last-modified / etag evidence
import math as _m
lm = collections.Counter((b["gen"], b["last_modified"][:7]) for b in Bn)
P("Last-Modified month by generation: " + ", ".join(f"{k[0]}:{k[1]}={v}" for k, v in sorted(lm.items())))
lmd = collections.Counter((b["gen"], b["last_modified"]) for b in Bn if b["last_modified"] >= "2026-10")
P("October Last-Modified days: " + ", ".join(f"{k[0]}:{k[1]}={v}" for k, v in sorted(lmd.items())))
chk = collections.Counter()
for b in Bn:
    tot = int(b["total"]); parts = int(b["etag_parts"])
    p64 = _m.ceil(tot / 67108864)
    p8 = _m.ceil(tot / 8388608)
    kind = "single-part" if parts == 0 else ("64MiB parts" if parts == p64 else ("8MiB parts" if parts == p8 else "other"))
    chk[(b["gen"], b["last_modified"][:7], kind)] += 1
P("ETag multipart signature (parts==ceil(size/64MiB) => rewritten by the migration script's 64 MiB transfer; ==ceil(size/8MiB) => original uploader; no '-N' => single PUT): "
  + ", ".join(f"{k[0]}/{k[1]}/{k[2]}={v}" for k, v in sorted(chk.items())))
sp = [b for b in Bn if int(b["etag_parts"]) == 0]
P(f"single-part bundles: {len(sp)}; max size {fmt_b(max(int(b['total']) for b in sp))} (single PUT, multipart threshold 64 MiB = 67.1 MB).")
P()

# ---------------------------------------------------------------- 2. restricted
P("## T3. Restricted-type members in the public bundles")
P()
nr = sum(int(r["restricted"]) for r in M)
nl = sum(int(r["restricted_loose"]) for r in M)
P(f"- members matching the repo rule `singlet._restricted.is_restricted_path`: {nr} of {len(M)}; bundles with any: 0 of {n}. "
  f"Upper 95% bound on the fraction of bundles (Clopper-Pearson, 0 of {n}): {100*(1-0.025**(1/n)):.2f}%.")
loosecats = collections.Counter(r["category"] for r in M if r["restricted_loose"] == "1")
P(f"- looser name test (snp_, vcf/bcf, donor*_coverage, ase_counts, mt_consensus, mt_variants, mt_reference, genotype): {nl} members, categories {dict(loosecats)}; "
  f"bytes {fmt_b(sum(int(r['csize']) for r in M if r['restricted_loose']=='1'))} (public by the repo allowlist because they sit at the sample root, not in donor/ or mt/).")
names_pub = collections.Counter(r["category"] for r in M if r["category"].startswith(("donor/", "mt/")) or r["category"].startswith("donor"))
P(f"- donor/ and mt/ members that ARE present (the public allowlist): {dict(names_pub)}")
P()

# ---------------------------------------------------------------- 3. method
P("## T4. ZIP compression method by member group")
P()
P("| group | STORED bytes | DEFLATE bytes | other-method bytes | DEFLATE unc bytes | DEFLATE ratio |")
P("|---|---|---|---|---|---|")
byg = collections.defaultdict(lambda: collections.Counter())
for r in M:
    g = r["group"]; m = r["method"]
    byg[g]["c" + m] += int(r["csize"]); byg[g]["u" + m] += int(r["usize"])
tot_st = sum(v["c0"] for v in byg.values()); tot_de = sum(v["c8"] for v in byg.values())
tot_ot = sum(sum(c for k, c in v.items() if k.startswith("c") and k not in ("c0", "c8")) for v in byg.values())
for g in sorted(byg, key=lambda g: -(byg[g]["c0"] + byg[g]["c8"])):
    v = byg[g]
    oth = sum(c for k, c in v.items() if k.startswith("c") and k not in ("c0", "c8"))
    P(f"| {g} | {fmt_b(v['c0'])} | {fmt_b(v['c8'])} | {fmt_b(oth)} | {fmt_b(v['u8'])} | {v['u8']/max(v['c8'],1):.2f} |")
P()
tot = tot_st + tot_de + tot_ot
q_st = np.zeros(n); q_de = np.zeros(n)
for r in M:
    if r["method"] == "0": q_st[gi[r["gse"]]] += int(r["csize"])
    elif r["method"] == "8": q_de[gi[r["gse"]]] += int(r["csize"])
e1 = ratio_ci(q_st); e2 = ratio_ci(q_de)
P(f"Total: STORED {fmt_b(tot_st)} ({pct(e1[0])} of bundle bytes, CI {pct(e1[1])} to {pct(e1[2])}), DEFLATE {fmt_b(tot_de)} ({pct(e2[0])}, CI {pct(e2[1])} to {pct(e2[2])}), other methods {fmt_b(tot_ot)}.")
# stored but not .1pz?
stored_non1pz = collections.Counter()
for r in M:
    if r["method"] == "0" and not r["category"].endswith(".1pz"): stored_non1pz[r["category"]] += int(r["csize"])
deflate_1pz = sum(int(r["csize"]) for r in M if r["method"] == "8" and r["category"].endswith(".1pz"))
P(f"STORED non-.1pz members: {dict(stored_non1pz)}; DEFLATED .1pz members: {fmt_b(deflate_1pz)}.")
P()
# entropy-coded share = .1pz bytes (zstd frames inside, stored)
q_pz = np.zeros(n)
for r in M:
    if r["category"].endswith(".1pz"): q_pz[gi[r["gse"]]] += int(r["csize"])
e = ratio_ci(q_pz)
P(f"Already entropy-coded content (.1pz = zstd frames, stored): {pct(e[0])} of bytes (CI {pct(e[1])} to {pct(e[2])}); text only deflated: "
  f"{pct(e2[0])} (CI {pct(e2[1])} to {pct(e2[2])}); the rest is container overhead and stored text.")
P()

# ---------------------------------------------------------------- 4. sizes
P("## T5. Size distributions")
P()
qs = [0, 10, 25, 50, 75, 90, 99, 100]
P("Bundle size quantiles (MB): " + ", ".join(f"p{q}={np.percentile(btot,q)/1e6:.1f}" for q in qs))
for lab, th in (("512 MB (5.12e8)", 512e6), ("512 MiB", 512 * 2**20), ("5 GB (Enterprise limit 5e9)", 5e9)):
    m_ = btot > th
    fb = ratio_ci(m_.astype(float), b=np.ones(n)); fy = ratio_ci(btot * m_)
    P(f"- bundles over {lab}: {int(m_.sum())} of {n} = {pct(fb[0])} of bundles (CI {pct(fb[1])} to {pct(fb[2])}); {pct(fy[0])} of bytes (CI {pct(fy[1])} to {pct(fy[2])}); "
      f"atlas projection {fb[0]*N_ATLAS:.0f} bundles ({fb[1]*N_ATLAS:.0f} to {fb[2]*N_ATLAS:.0f}), {fmt_b(fy[0]*B_ATLAS)} ({fmt_b(fy[1]*B_ATLAS)} to {fmt_b(fy[2]*B_ATLAS)})")
P()
for g_ in ("A", "B"):
    mk = gen == g_
    m_ = btot[mk] > 512e6
    P(f"- gen {g_}: {int(m_.sum())} of {int(mk.sum())} bundles over 512 MB; bytes in them {pct((btot[mk]*m_).sum()/btot[mk].sum())} of the generation's bytes")
P()
ns = np.array([int(b["n_samples"]) for b in Bn]); nm = np.array([int(b["n_members"]) for b in Bn])
cd = np.array([int(b["cd_size"]) for b in Bn]); ov = np.array([int(b["overhead"]) for b in Bn])
P("Samples per bundle quantiles: " + ", ".join(f"p{q}={np.percentile(ns,q):.0f}" for q in qs) + f"; total samples in sample {ns.sum()}")
P("Members per bundle quantiles: " + ", ".join(f"p{q}={np.percentile(nm,q):.0f}" for q in qs))
for g_ in ("A", "B"):
    mk = gen == g_
    P(f"- gen {g_}: members per sample {nm[mk].sum()/ns[mk].sum():.1f} (incl. 3 study-level per bundle), samples per bundle median {np.median(ns[mk]):.0f}, mean {ns[mk].mean():.1f}")
P("Central directory size quantiles (kB): " + ", ".join(f"p{q}={np.percentile(cd,q)/1e3:.1f}" for q in qs))
P(f"CD bytes per member: {cd.sum()/nm.sum():.1f} B; CD / bundle: median {np.median(cd/btot)*100:.4f}%, max {np.max(cd/btot)*100:.4f}% ; sum CD / sum bundle = {pct(cd.sum()/btot.sum())}")
nt = int(sum(1 for b in Bn if b["cd_in_tail"] == "0"))
