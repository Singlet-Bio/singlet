#!/usr/bin/env python
"""Generate kernels/e2_tables.h: integer constant tables for the E2 coder (no libm on the decode path)."""
import math
EX = [round(2**31 * 2 ** (-k / 1024)) for k in range(1025)]          # 2^31 * 2^(-k/1024)
LG = [round(2**24 * math.log2(1 + k / 1024)) for k in range(1025)]    # 2^24 * log2(1 + k/1024)
def arr(name, vals):
    s = f"static const uint32_t {name}[{len(vals)}] = {{"
    for i, v in enumerate(vals):
        if i % 8 == 0: s += "\n  "
        s += f"{v}u, "
    return s + "\n};\n"
with open("kernels/e2_tables.h", "w") as f:
    f.write("// Generated by tools/e2_gen_tables.py - integer constants only. Do not edit.\n#pragma once\n#include <cstdint>\nnamespace cs { namespace e2 {\n")
    f.write(arr("E2_EX", EX)); f.write(arr("E2_LG", LG))
    f.write("}}\n")
print("ok", EX[0], EX[1024], LG[0], LG[1024])
