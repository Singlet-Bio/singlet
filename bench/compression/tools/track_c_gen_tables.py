#!/usr/bin/env python
"""Generate kernels/track_c_tables.h: integer constant tables for the Track C decoder (no floating point at run time)."""
import math, sys
QF = 40
STEP_SHIFT = 29                       # exp table grid in Q40: step = 2^29 (= 2^-11)
LN2_Q40 = round(math.log(2) * (1 << QF))
NSTEP = (LN2_Q40 >> STEP_SHIFT) + 2   # entries needed to cover [0, ln2) plus guard
exp_tab = [round(math.exp(-(i << STEP_SHIFT) / (1 << QF)) * (1 << 48)) for i in range(NSTEP + 1)]
ln_tab = [round(math.log(1 + i / 1024) * (1 << QF)) for i in range(1025)]
exp2_tab = [round(2 ** (-i / 2048) * (1 << 48)) for i in range(2049)]
NB = 32
th = [max(1, math.ceil(2 ** ((i - 1) * 14 / NB) - 1e-9)) for i in range(1, NB + 1)]   # smallest nnz of bucket i (1-based)
def arr(name, vals, typ="uint64_t"):
    s = f"static const {typ} {name}[{len(vals)}] = {{"
    for i, v in enumerate(vals):
        if i % 6 == 0: s += "\n  "
        s += f"{v}ull, " if typ == "uint64_t" else f"{v}, "
    return s + "\n};\n"
with open("kernels/track_c_tables.h", "w") as f:
    f.write("// Generated by tools/track_c_gen_tables.py - integer constants only. Do not edit.\n#pragma once\n#include <cstdint>\nnamespace cs { namespace tc {\n")
    f.write(f"static const int TC_QF = {QF}; static const int TC_STEP_SHIFT = {STEP_SHIFT};\nstatic const uint64_t TC_LN2_Q40 = {LN2_Q40}ull;\nstatic const int TC_NEXP = {NSTEP};\nstatic const int TC_NB = {NB};\n")
    f.write(arr("TC_EXP", exp_tab)); f.write(arr("TC_LN", ln_tab)); f.write(arr("TC_EXP2", exp2_tab)); f.write(arr("TC_BTH", th, "uint32_t"))
    f.write("}}\n")
print("ok", NSTEP, th)
