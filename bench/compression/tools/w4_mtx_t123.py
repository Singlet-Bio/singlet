#!/usr/bin/env python
"""w4_mtx tests 1-3: filtered mtx regeneration, raw barcodes vs whitelist, features vs feature_vocab.json.
    python -P tools/w4_mtx_t123.py <GSE.GSM> ...
Output: results/w4_mtx_t123.tsv (one line per check) and stdout.
"""
import os, sys, json, struct, zstandard
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); BC = os.path.dirname(HERE)
CORP = os.path.join(BC, "corpus_w4_mtx"); RES = os.path.join(BC, "results")
P = "star_Solo.out__Gene__"

def rd(d, n): return open(os.path.join(CORP, d, n), "rb").read()

def load_whitelist_codes(name):
    b = open(os.path.join(RES, f"track_a_whitelist_{name}.bin"), "rb").read()
    nl = struct.unpack_from("<H", b, 8)[0]; p = 10 + nl
    count, zlen, rawlen = struct.unpack_from("<IQQ", b, p); p += 20
    raw = zstandard.ZstdDecompressor().decompress(b[p:p + zlen], max_output_size=rawlen + 16)
    arr = np.frombuffer(raw, dtype=np.uint8)
    cont = (arr & 0x80) != 0; ends = np.flatnonzero(~cont); starts = np.concatenate([[0], ends[:-1] + 1])
    out = np.zeros(len(ends), dtype=np.uint64)
    for k in range(int((ends - starts).max()) + 1):
        idx = starts + k; v = idx <= ends
        out[v] |= (arr[idx[v]] & 0x7F).astype(np.uint64) << np.uint64(7 * k)
    codes = np.cumsum(np.concatenate([[out[0]], out[1:] + 1])).astype(np.uint64)
    assert len(codes) == count
    return codes

def codes_to_text(codes):
    n = len(codes); a = np.empty((n, 17), dtype=np.uint8); a[:, 16] = 10
    tab = np.frombuffer(b"ACGT", dtype=np.uint8)
    c = codes.copy()
    for i in range(15, -1, -1):
        a[:, i] = tab[(c & np.uint64(3)).astype(np.int64)]; c >>= np.uint64(2)
    return a.tobytes()

def parse_mtx(b):
    lines_end = 0; hdr = []
    pos = 0
    while True:
        e = b.index(b"\n", pos); ln = b[pos:e + 1]; pos = e + 1; hdr.append(ln)
        if not ln.startswith(b"%"): break
    nr, nc, nnz = map(int, hdr[-1].split())
    t = np.fromstring(b[pos:], dtype=np.int64, sep=" ").reshape(-1, 3) if nnz else np.zeros((0, 3), np.int64)
    assert len(t) == nnz, (len(t), nnz)
    return hdr, nr, nc, nnz, t

def fmt_mtx(hdr_lines, t):
    return b"".join(hdr_lines) + ("\n".join("%d %d %d" % (a, b, c) for a, b, c in t.tolist()) + "\n").encode() if len(t) else b"".join(hdr_lines)

def main():
    rows = []
    def rec(s, test, item, result, detail=""):
        rows.append((s, test, item, result, detail)); print(f"[{s}] {test} {item}: {result} {detail}", flush=True)
    for d in sys.argv[1:]:
        s = d
        sj = json.load(open(os.path.join(CORP, d.split(".")[0], "manifest.json")))
        build = sj.get("reference_build")
        rb = rd(d, P + "raw__barcodes.tsv"); fb = rd(d, P + "filtered__barcodes.tsv")
        rbl = rb.decode().split("\n")[:-1]; fbl = fb.decode().split("\n")[:-1]
        rmtx = rd(d, P + "raw__matrix.mtx"); fmtx = rd(d, P + "filtered__matrix.mtx")
        hdr, nr, nc, nnz, T = parse_mtx(rmtx)
        fhdr, fnr, fnc, fnnz, FT = parse_mtx(fmtx)
        rec(s, "t1", "dims", "info", f"build={build} raw {nr}x{nc} nnz={nnz}; filtered {fnr}x{fnc} nnz={fnnz}; raw bc lines={len(rbl)} filtered bc lines={len(fbl)}")
        pos = {b: i + 1 for i, b in enumerate(rbl)}
        idx = np.array([pos.get(b, -1) for b in fbl], dtype=np.int64)
        rec(s, "t1", "filtered barcodes all in raw", str(bool((idx > 0).all())), f"missing={(idx<=0).sum()}")
        rec(s, "t1", "filtered barcodes in raw order", str(bool((np.diff(idx) > 0).all())))
        # regenerate: keep columns in idx, renumber in the order of idx (raw order if monotone)
        keep = np.zeros(nc + 2, dtype=np.int64); newid = np.zeros(nc + 2, dtype=np.int64)
        newid[idx] = np.arange(1, len(idx) + 1)
        sel = newid[T[:, 1]] > 0
        R = T[sel].copy(); R[:, 1] = newid[R[:, 1]]
        # header: copy raw header lines except dims line
        newhdr = hdr[:-1] + [("%d %d %d\n" % (nr, len(idx), len(R))).encode()]
        out = fmt_mtx(newhdr, R)
        ok = out == fmtx
        rec(s, "t1", "filtered/matrix.mtx regenerated byte-identical", str(ok), f"len {len(out)} vs {len(fmtx)}")
        if not ok:
            # diagnose
            same_hdr = b"".join(newhdr) == b"".join(fhdr)
            rec(s, "t1", "header identical", str(same_hdr), f"{b''.join(newhdr)!r} vs {b''.join(fhdr)!r}")
            rec(s, "t1", "triplets equal", str(len(R) == len(FT) and bool((R == FT).all())))
        rec(s, "t1", "filtered/barcodes.tsv regenerated from index list", str("\n".join(rbl[i - 1] for i in idx) + "\n" == fb.decode()))
        # cell_calls
        cc = rd(d, "cell_calls.tsv").decode().split("\n")[1:-1]
        cc = [l.split("\t") for l in cc]
        called = [r[0] for r in cc if r[1] == "TRUE"]
        allcc = [r[0] for r in cc]
        rec(s, "t1", "cell_calls.tsv rows", "info", f"rows={len(cc)} TRUE={len(called)} call_methods={sorted(set(r[4] for r in cc))}")
        rec(s, "t1", "filtered barcodes == cell_calls TRUE set", str(set(called) == set(fbl)), f"|called|={len(called)} |filtered|={len(fbl)} |inter|={len(set(called)&set(fbl))}")
        rec(s, "t1", "cell_calls rows == filtered barcodes (set)", str(set(allcc) == set(fbl)), f"|cc rows|={len(allcc)}")
        rec(s, "t1", "cell_calls row order == filtered order", str(allcc == fbl))
        # T2
        n = len(rbl)
        wl = None
        for name in ("3M-february-2018", "737K-august-2016"):
            if n == {"3M-february-2018": 3686400, "737K-august-2016": 737280}[name]: wl = name
        if wl:
            txt = codes_to_text(load_whitelist_codes(wl))
            rec(s, "t2", f"raw/barcodes.tsv == whitelist {wl} (sorted, track_a model)", str(txt == rb), f"lines {n}; sorted_lex={rbl==sorted(rbl)}")
        else:
            rec(s, "t2", "raw/barcodes.tsv whitelist", "no track_a model for this count", f"lines {n}; sorted_lex={rbl==sorted(rbl)} unique={len(set(rbl))}")
        # T3
        rf = rd(d, P + "raw__features.tsv"); ff = rd(d, P + "filtered__features.tsv")
        rec(s, "t3", "raw features == filtered features", str(rf == ff), f"{len(rf)} bytes")
        voc = json.load(open(os.path.join(CORP, d.split(".")[0], "feature_vocab.json")))
        rec(s, "t3", "vocab top-level keys", "info", f"{list(voc.keys())[:10] if isinstance(voc, dict) else type(voc)}")
        for k, v in (voc.items() if isinstance(voc, dict) else []):
            rec(s, "t3", f"vocab[{k}]", "info", f"type={type(v).__name__} len={len(v) if hasattr(v,'__len__') else ''} head={str(v)[:200]}")
        rec(s, "t3", "features n_lines vs mtx nrows", str(rf.count(b"\n") == nr), f"{rf.count(chr(10).encode())} vs {nr}")
    with open(os.path.join(RES, "w4_mtx_t123.tsv"), "a") as f:
        for r in rows: f.write("\t".join(map(str, r)) + "\n")

main()
