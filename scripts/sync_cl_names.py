"""Write r/inst/extdata/cl_names.tsv: the Cell Ontology names of the per-cell label guide's nodes, so the R client can name every
level of a cell's CL path (the Python client reads python/singlet/celllabels/data/cl.json.gz directly).

    python scripts/sync_cl_names.py            # rewrite the table
    python scripts/sync_cl_names.py --check    # exit 1 if it is out of date (tests/python/test_s1_labels.py runs this)
"""

from __future__ import annotations

import gzip
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "python" / "singlet" / "celllabels" / "data"
OUT = ROOT / "r" / "inst" / "extdata" / "cl_names.tsv"


def render() -> str:
    with gzip.open(DATA / "cellguide.json.gz", "rt", encoding="utf-8") as fh:
        guide = json.load(fh)
    with gzip.open(DATA / "cl.json.gz", "rt", encoding="utf-8") as fh:
        cl = json.load(fh)
    ids = sorted({n["cl"] for n in guide["nodes"] if n.get("cl")})
    lines = [
        "# Cell Ontology names of the per-cell label guide nodes (%s; guide %s). Generated by scripts/sync_cl_names.py."
        % (cl["version"], guide.get("guide_version")),
        "id\tname",
    ]
    for i in ids:
        lines.append("%s\t%s" % (i, (cl["terms"].get(i) or {}).get("name", i)))
    return "\n".join(lines) + "\n"


def main(argv) -> int:
    text = render()
    if "--check" in argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur != text:
            print("%s is out of date: run python scripts/sync_cl_names.py" % OUT.relative_to(ROOT))
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s" % OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
