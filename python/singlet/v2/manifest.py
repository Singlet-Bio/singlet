"""Study manifest ``v2/m/<GSE>.json`` (docs/format-v2.md section 7).

``rev`` is the digest of the sorted list of sample object keys plus the study-file contents; it does not depend on timestamps, so a
re-migration that produces the same objects keeps the same ``rev`` and clients can answer "unchanged".

Study-level legacy files (``manifest.json``, ``study_meta.json``, ``feature_vocab.json``, anything else outside ``samples/``) live in
``study_files``; each entry is exactly one of::

    {"recipe": id, "params": {...}, "needs": [...], "size", "crc32", "sha256"}      derived (regenerated by the recipe)
    {"json": <object>, "dumps": {indent, ensure_ascii, sort_keys, separators}, "size", "crc32", "sha256"}   inline JSON that
                                                                                     ``json.dumps`` reproduces byte for byte
    {"zstd_b64": "...", "size", "crc32", "sha256"}                                    stored (zstd-19, base64)
"""

from __future__ import annotations

import base64
import hashlib
import json
from typing import Optional

from . import util

FORMAT = "singlet-v2"
MANIFEST_VERSION = 1

_DUMPS_VARIANTS = (
    {"indent": 2, "ensure_ascii": True, "sort_keys": False},
    {"indent": 2, "ensure_ascii": False, "sort_keys": False},
    {"indent": 2, "ensure_ascii": True, "sort_keys": True},
    {"indent": None, "ensure_ascii": True, "sort_keys": False, "separators": [", ", ": "]},
    {"indent": None, "ensure_ascii": True, "sort_keys": False, "separators": [",", ":"]},
    {"indent": None, "ensure_ascii": False, "sort_keys": False, "separators": [",", ":"]},
    {"indent": 1, "ensure_ascii": True, "sort_keys": False},
    {"indent": 4, "ensure_ascii": True, "sort_keys": False},
)


def _dumps(obj, v: dict) -> bytes:
    kw = dict(v)
    if "separators" in kw:
        kw["separators"] = tuple(kw["separators"])
    return json.dumps(obj, **kw).encode("utf-8")


def study_file_entry(data: bytes, plan: Optional[tuple] = None) -> dict:
    """Entry for one study-level file. ``plan`` = (recipe_id, params, needs) when a verified recipe regenerates it."""
    ent = {"size": len(data), "crc32": util.crc32(data), "sha256": hashlib.sha256(data).hexdigest()}
    if plan is not None:
        ent.update({"recipe": plan[0], "params": plan[1], "needs": list(plan[2])})
        return ent
    try:
        obj = json.loads(data.decode("utf-8"))
    except Exception:
        obj = None
    if obj is not None and (isinstance(obj, (dict, list))):
        for v in _DUMPS_VARIANTS:
            try:
                if _dumps(obj, v) == data and len(data) < 200_000:
                    ent.update({"json": obj, "dumps": v})
                    return ent
            except Exception:
                continue
    ent["zstd_b64"] = base64.b64encode(util.zstd_compress(data, 19)).decode("ascii")
    return ent


def study_file_bytes(ent: dict, regenerate=None) -> bytes:
    """Bytes of a study file. ``regenerate(recipe_id, params)`` is required for derived entries. The result is checked."""
    if "recipe" in ent:
        if regenerate is None:
            raise ValueError("derived study file needs a regenerate callable")
        data = regenerate(ent["recipe"], ent.get("params", {}))
    elif "json" in ent:
        data = _dumps(ent["json"], ent["dumps"])
    else:
        data = util.zstd_decompress(
            base64.b64decode(ent["zstd_b64"]), max_output_size=ent["size"] or 1
        )
    if len(data) != ent["size"] or util.crc32(data) != ent["crc32"]:
        raise ValueError("study file fails its size/CRC check")
    return data


def compute_rev(sample_keys: list, study_files: dict) -> str:
    """16 hex: SHA-256 over ``SGMREV1``, the sorted sample keys, and ``name`` + sha256 of every study file (sorted by name)."""
    h = hashlib.sha256(b"SGMREV1\n")
    for k in sorted(sample_keys):
        h.update(k.encode("utf-8") + b"\n")
    for name in sorted(study_files):
        h.update(name.encode("utf-8") + b"\0" + study_files[name]["sha256"].encode("ascii") + b"\n")
    return h.hexdigest()[:16]


def build_manifest(
    gse: str,
    samples: list,
    study_files: dict,
    reference_build: str,
    pipeline: dict,
    packs: dict,
    legacy: dict,
    created_at: str,
) -> dict:
    keys = [s["key"] for s in samples]
    return {
        "format": FORMAT,
        "manifest_version": MANIFEST_VERSION,
        "gse": gse,
        "rev": compute_rev(keys, study_files),
        "created_at": created_at,
        "reference_build": reference_build,
        "pipeline": pipeline,
        "packs": packs,
        "study_files": study_files,
        "samples": samples,
        "legacy": legacy,
    }


def dumps_manifest(m: dict) -> bytes:
    return (json.dumps(m, indent=1, sort_keys=False, ensure_ascii=False) + "\n").encode("utf-8")


def loads_manifest(data: bytes) -> dict:
    m = json.loads(data.decode("utf-8"))
    if m.get("format") != FORMAT:
        raise ValueError("not a singlet-v2 manifest")
    return m


def sample_entry(
    gsm: str, key: str, obj: bytes, n_columns: int, n_called: int, members: dict, stats: dict
) -> dict:
    return {
        "gsm": gsm,
        "key": key,
        "bytes": len(obj),
        "sha256": hashlib.sha256(obj).hexdigest(),
        "n_columns": n_columns,
        "n_called": n_called,
        "members": members,
        "stats": stats,
    }
