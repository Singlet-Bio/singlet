class _Writer:
    id = ""
    label = ""

    def write(
        self, m: Matrix, level=3, chunk_cols=1024, threads=4, user_kv=None
    ) -> bytes:  # pragma: no cover
        raise NotImplementedError

    def calibrate(self) -> str:
        data = self.write(_calibration_matrix())
        self.id = hashlib.sha256(data).hexdigest()[:8]
        self.label = KNOWN.get(self.id, "unlabelled")
        return self.id


class PydWriter(_Writer):
    kind = "pyd"

    def write(self, m, level=3, chunk_cols=1024, threads=4, user_kv=None):
        pz = load_pz()
        fd, path = tempfile.mkstemp(suffix=".1pz")
        os.close(fd)
        try:
            ok = pz.write_1pz(
                path,
                np.asarray(m.indptr, dtype=np.int32),
                np.asarray(m.indices, dtype=np.int32),
                np.asarray(m.data, dtype=np.uint32),
                int(m.shape[0]),
                int(m.shape[1]),
                rownames=m.rownames or None,
                colnames=m.colnames or None,
                zstd_level=level,
                chunk_cols=chunk_cols,
                threads=threads,
                user_meta=user_kv or None,
            )
            if not ok:
                raise RuntimeError("write_1pz failed")
            with open(path, "rb") as f:
                return f.read()
        finally:
            os.unlink(path)


def _pack_names(names):
    out = [struct.pack("<I", len(names))]
    for s in names:
        b = s.encode("utf-8")
        out.append(struct.pack("<I", len(b)))
        out.append(b)
    return b"".join(out)


class ExeWriter(_Writer):
    kind = "exe"

    def __init__(self, exe):
        self.exe = exe

    def write(self, m, level=3, chunk_cols=1024, threads=4, user_kv=None):
        fd, inp = tempfile.mkstemp(suffix=".bin")
        os.close(fd)
        outp = inp + ".1pz"
        try:
            with open(inp, "wb") as f:
                nnz = int(m.indptr[-1]) if len(m.indptr) else 0
                f.write(
                    b"PZW1"
                    + struct.pack(
                        "<IIiiiQ", int(m.shape[0]), int(m.shape[1]), level, chunk_cols, threads, nnz
                    )
                )
                f.write(np.asarray(m.indptr, dtype="<i4").tobytes())
                f.write(np.asarray(m.indices, dtype="<i4").tobytes())
                f.write(np.asarray(m.data, dtype="<u4").tobytes())
                f.write(_pack_names(list(m.rownames or [])))
                f.write(_pack_names(list(m.colnames or [])))
                kv = user_kv or {}
                f.write(struct.pack("<I", len(kv)))
                for k, v in sorted(kv.items()):
                    for s in (k, v):
                        b = s.encode("utf-8")
                        f.write(struct.pack("<I", len(b)) + b)
            r = subprocess.run([self.exe, inp, outp], capture_output=True)
            if r.returncode != 0:
                raise RuntimeError("pzw helper failed: %r" % r.stderr[-300:])
            with open(outp, "rb") as f:
                return f.read()
        finally:
            for p in (inp, outp):
                if os.path.exists(p):
                    os.unlink(p)


_WRITERS = None


def available_writers(refresh=False, autobuild=None) -> dict:
    """{calibration id: writer} for every writer usable on this machine."""
    global _WRITERS
    if _WRITERS is not None and not refresh:
        return _WRITERS
    ws = []
    try:
        ws.append(PydWriter())
    except Exception:
        pass
    exes = [p for p in os.environ.get("SINGLET_PZW_EXES", "").split(os.pathsep) if p]
    if autobuild is None:
        autobuild = os.environ.get("SINGLET_PZW_AUTOBUILD", "1") != "0"
    if autobuild:
        e = auto_build_exe()
        if e:
            exes.append(e)
    for e in exes:
        if os.path.exists(e):
            ws.append(ExeWriter(e))
    out = {}
    for w in ws:
        try:
            w.calibrate()
        except Exception as ex:  # a broken writer is simply not available
            sys.stderr.write("writer %r unusable: %s\n" % (w, ex))
            continue
        out.setdefault(w.id, w)
    _WRITERS = out
    return out


def write_legacy_1pz(
    m: Matrix, writer_id: str, level=3, chunk_cols=1024, threads=4, user_kv=None
) -> bytes:
    w = available_writers().get(writer_id)
    if w is None:
        raise LookupError(
            "no .1pz writer with calibration id %s on this machine (have %s)"
            % (writer_id, sorted(available_writers()))
        )
    return w.write(m, level, chunk_cols, threads, user_kv)


def parse_header(b: bytes) -> dict:
    """The fields of the 96-byte header that a re-emission must be told: level, chunk_cols, vt_code, ..."""
    f = struct.unpack_from("<IHBBIIQBBHIIIIIQIIQII16s", b, 0)
    names = (
        "magic version vt_code flags m n nnz ptr_width codec_level pad0 num_chunks perm_z_sz ptr_z_sz chunk_cols "
        "feature_flags metadata_offset metadata_z_sz colsums_z_sz transpose_offset transpose_z_sz transpose_chunks reserved"
    ).split()
    return dict(zip(names, f))
