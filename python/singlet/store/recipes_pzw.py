"""Legacy TP1Z (.1pz) byte writers for the store migration recipes (owner: W3).

A derived legacy ``.1pz`` member (``splice_psi.1pz``) can be regenerated either as a *matrix* (the decoded canonical
CSC; this is the bit-equivalence criterion of the migration) or as the *container bytes*.  The container bytes
depend on the zstd build that wrote the file (1.5.5/1.5.6 versus 1.5.7 differ in about a third of the frames, see
bench/compression/notes/track_a.md section 6), so a byte-level recipe has to name the writer it needs.

A *writer* here is any implementation of ``include/singlet/pileup/pz_writer.h:write_1pz`` linked against some zstd:

  * ``PydWriter``  the compiled ``singlet._pz.write_1pz`` (whatever zstd it was built with; 1.5.7 on this laptop)
  * ``ExeWriter``  a small helper executable built from ``pz_writer.h`` (source embedded below) against another
                   libzstd.  ``auto_build_exe()`` builds one with the Rtools GCC toolchain and its static zstd 1.5.5
                   when that toolchain is present; ``SINGLET_PZW_EXES`` (os.pathsep separated) lists prebuilt helpers.

Writers are identified by *calibration id*: the first 8 hex digits of the SHA-256 of the file the writer produces for a
fixed synthetic matrix.  That is a property of the zstd build and of the writer code, and survives moving to another
machine, which a version string would not.  Known ids are labelled in ``KNOWN`` for the reports.
"""

from __future__ import annotations

import hashlib
import os
