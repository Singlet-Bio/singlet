HELPER_SRC = r"""
// pzw: write a .1pz with include/singlet/pileup/pz_writer.h (generated by python/singlet/store/recipes_pzw.py)
// usage: pzw <in.bin> <out.1pz>
// in.bin: "PZW1" u32 m u32 n i32 level i32 chunk_cols i32 threads u64 nnz
//         i32 indptr[n+1] i32 indices[nnz] u32 data[nnz]
//         u32 n_rownames {u32 len bytes}  u32 n_colnames {u32 len bytes}  u32 n_kv {u32 klen k u32 vlen v}
#include <cstdint>
#include <cstdio>
#include <fstream>
#include <map>
#include <string>
#include <vector>
#include "singlet/pileup/pz_writer.h"
static bool rd(std::ifstream& f, void* p, size_t n) { f.read((char*)p, (std::streamsize)n); return (bool)f; }
static bool rdstr(std::ifstream& f, std::string& s) { uint32_t l; if (!rd(f, &l, 4)) return false; s.resize(l); return l == 0 || rd(f, &s[0], l); }
int main(int argc, char** argv) {
    if (argc < 3) return 2;
    std::ifstream f(argv[1], std::ios::binary);
    char mg[4]; if (!rd(f, mg, 4) || std::string(mg, 4) != "PZW1") return 3;
    uint32_t m, n; int32_t level, cc, th; uint64_t nnz;
    rd(f, &m, 4); rd(f, &n, 4); rd(f, &level, 4); rd(f, &cc, 4); rd(f, &th, 4); rd(f, &nnz, 8);
    std::vector<int32_t> indptr(n + 1), indices(nnz); std::vector<uint32_t> data(nnz);
    rd(f, indptr.data(), 4 * (n + 1)); if (nnz) { rd(f, indices.data(), 4 * nnz); rd(f, data.data(), 4 * nnz); }
    std::vector<std::string> rn, cn; uint32_t k;
    rd(f, &k, 4); rn.resize(k); for (auto& s : rn) rdstr(f, s);
    rd(f, &k, 4); cn.resize(k); for (auto& s : cn) rdstr(f, s);
    std::map<std::string, std::string> kv; rd(f, &k, 4);
    for (uint32_t i = 0; i < k; ++i) { std::string a, b; rdstr(f, a); rdstr(f, b); kv[a] = b; }
    if (!f) return 4;
    bool ok = singlet::pz::write_1pz<uint32_t>(argv[2], m, n, indptr, indices, data, rn, cn, level, cc, th, kv);
    return ok ? 0 : 1;
}
"""

_RTOOLS = r"C:\RBuildTools\4.4\x86_64-w64-mingw32.static.posix"


def _repo_include():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.abspath(os.path.join(here, "..", "..", ".."))
    inc = os.path.join(root, "include")
    return inc if os.path.isdir(os.path.join(inc, "singlet", "pileup")) else None


def cache_dir():
    d = util.env("RECIPES_CACHE") or os.path.join(tempfile.gettempdir(), "singlet_store_recipes")
    os.makedirs(d, exist_ok=True)
    return d


def auto_build_exe(force=False):
    """Build the helper with the Rtools GCC + static zstd (1.5.5) when available.  Returns the exe path or None."""
    inc = _repo_include()
    if inc is None or not os.path.isdir(_RTOOLS):
        return None
    d = cache_dir()
    src = os.path.join(d, "pzw.cpp")
    exe = os.path.join(d, "pzw_rtools.exe")
    if not force and os.path.exists(exe) and os.path.exists(src):
        with open(src) as f:
            if f.read() == HELPER_SRC:
                return exe
    with open(src, "w") as f:
        f.write(HELPER_SRC)
    env = dict(os.environ)
    env["PATH"] = _RTOOLS + r"\bin;C:\RBuildTools\4.4\usr\bin;" + env.get("PATH", "")
    cmd = [
        _RTOOLS + r"\bin\g++.exe",
        "-std=c++20",
        "-O2",
        "-DNDEBUG",
        "-I",
        inc,
        "-I",
        _RTOOLS + r"\include",
        src,
        "-o",
        exe,
        _RTOOLS + r"\lib\libzstd.a",
        "-lpthread",
        "-static",
    ]
    r = subprocess.run(cmd, env=env, capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write("pzw helper build failed:\n" + r.stderr[-2000:])
        return None
    return exe


def build_exe_system(out_path, cxx="g++", extra=()):
    """Build the helper on Linux/macOS against the system libzstd."""
    inc = _repo_include()
    src = os.path.join(cache_dir(), "pzw.cpp")
    with open(src, "w") as f:
        f.write(HELPER_SRC)
    cmd = [
        cxx,
        "-std=c++20",
        "-O2",
        "-DNDEBUG",
        "-I",
        inc,
        src,
        "-o",
        out_path,
        "-lzstd",
        "-lpthread",
        *extra,
    ]
    subprocess.run(cmd, check=True)
    return out_path


