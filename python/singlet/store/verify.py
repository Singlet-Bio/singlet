"""Independent check that a store output tree reproduces a legacy bundle exactly.

    python -m singlet.store.verify --bundle PATH_OR_URL --store DIR [--gse GSE] [--samples GSM,GSM] [--recipes MODULE|none]

``DIR`` is the output directory of ``singlet.store.migrate`` (it contains ``store/m``, ``store/s``, ``store/ref``). For every sample the legacy bundle
and the store objects are read again from scratch and compared:

* every legacy matrix member == the decoded store matrix: shape, ``indptr``, ``indices``, ``data``, row names, column names, key/values;
  the canonical digest (docs/format-store.md 4.6) is recomputed with a separate, deliberately plain implementation and must equal the
  digest in the member table and the matrix header;
* every other legacy member == the regenerated bytes (length, CRC-32 against the ZIP directory, full compare);
* derived ``.1pz`` members: the regenerated canonical matrix == the legacy matrix (decision D15: this is the pass criterion for every
  ``.1pz`` member, stored, pz2 or derived). Equality of the legacy *container bytes* is reported as an informational column
  (``Report.container``: equal / differs / unavailable / not_applicable) and never fails the run;
* the cells table: required columns recomputed from the legacy matrices / ``cell_calls.tsv`` and compared;
* study files regenerated from the manifest == the legacy study files; manifest ``rev``, object sizes and SHA-256, pack files
  (id = digest16 of the file, sha256 against ``index.json``) are re-derived.

The comparison logic here shares nothing with the writer: own ``.s1`` table parser, own digest, own cells recomputation, own manifest
checks. What it must share is the pz2 *decoder* (``singlet.store.codec``), pack expansion and the recipes: those are the things under test, and
everything they produce is compared against the legacy truth read with the compiled legacy reader (or the standard ``zipfile`` module).
Exit status 0 only if every check passed.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import io
import json
import os
import struct
import sys
import tempfile
import time
import zipfile
import zlib
from typing import Optional

import numpy as np
import zstandard


# ----------------------------------------------------------------------------------------------------------- reporting
class Report:
    def __init__(self):
        self.ok = 0
        self.fail = 0
        self.items = []  # (status, where, what)
        self.by_kind: dict = {}
        self.container: dict = {
            "equal": 0,
            "differs": 0,
            "unavailable": 0,
            "not_applicable": 0,
        }  # .1pz container bytes (informational)

    def check(self, cond: bool, where: str, what: str, kind: str = "") -> bool:
        if cond:
            self.ok += 1
            if kind:
                self.by_kind.setdefault(kind, [0, 0])[0] += 1
        else:
            self.fail += 1
            self.items.append(("FAIL", where, what))
            print("FAIL %s: %s" % (where, what), file=sys.stderr, flush=True)
            if kind:
                self.by_kind.setdefault(kind, [0, 0])[1] += 1
        return cond


# ----------------------------------------------------------------------------------------------------------- legacy view
class _Zip:
    def __init__(self, path: str):
        self.z = zipfile.ZipFile(path)
        self.infos = {i.filename: i for i in self.z.infolist()}

    def names(self):
        return list(self.infos)

    def read(self, n):
        return self.z.read(n)

    def info(self, n):
        i = self.infos[n]
        return i.file_size, i.CRC


class _Lb:
    def __init__(self, src):
        from .legacy import LegacyBundle

        self.b = LegacyBundle.open(src)

    def names(self):
        return list(self.b.entries)

    def read(self, n):
        return self.b.read(n)

    def info(self, n):
        e = self.b.entries[n]
        return e.size, e.crc32


def open_legacy(src: str):
    if os.path.isfile(src) and zipfile.is_zipfile(src):
        return _Zip(src)
    return _Lb(src)


def read_1pz(data: bytes) -> dict:
    """The legacy compiled reader through a temporary file (the oracle for matrices)."""
    from singlet import _pz

    fd, path = tempfile.mkstemp(suffix=".1pz")
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        return _pz.read_1pz(path)
    finally:
        os.unlink(path)


# ----------------------------------------------------------------------------------------------------------- own .s1 parser
def parse_s2(data: bytes) -> dict:
    magic, ver, flags, n, toff, tlen, flen, sid, _r = struct.unpack_from("<8sHHIQQQ16s8s", data, 0)
    if magic != b"SINGLET2" or ver != 1 or flags != 0 or toff != 64 or flen != len(data):
        raise ValueError("bad .s1 header")
    p = toff
    members = {}
    end = toff + tlen
    for _ in range(n):
        (nl,) = struct.unpack_from("<H", data, p)
        p += 2
        name = data[p : p + nl].decode("utf-8")
        p += nl
        kind, fl, off, ln, out_len, crc, dg, ml = struct.unpack_from("<BBQQQI16sI", data, p)
        p += struct.calcsize("<BBQQQI16sI")
        meta = json.loads(data[p : p + ml].decode("utf-8")) if ml else {}
        p += ml
        members[name] = dict(
            kind=kind, flags=fl, off=off, len=ln, out_len=out_len, crc=crc, digest=dg, meta=meta
        )
    if p != end:
        raise ValueError("member table length mismatch")
    prev_end = end
    for name, m in sorted(members.items(), key=lambda kv: kv[1]["off"]):
        if m["kind"] == 4:
            if m["off"] or m["len"]:
                raise ValueError("derived member %s has a body" % name)
            continue
        if m["len"] == 0:
            continue
        if m["off"] % 64 or m["off"] < prev_end or m["off"] + m["len"] > len(data):
            raise ValueError("member %s misplaced" % name)
        prev_end = m["off"] + m["len"]
    return {"sample_id": sid.rstrip(b"\0").decode(), "members": members}


# ----------------------------------------------------------------------------------------------------------- own canonical digest
def slow_digest(m, n, indptr, indices, data, vt, rownames, colnames, kv) -> bytes:
    h = hashlib.sha256()
    h.update(b"PZ2CANON1")
    nnz = int(indptr[n]) if n else 0
    h.update(struct.pack("<IIQB", m, n, nnz, vt))
    ids = np.asarray(indices).astype("<u4")
    vals = np.asarray(data).astype("<u4")
    ip = np.asarray(indptr).astype(np.int64)
    for j in range(n):
        a, b = int(ip[j]), int(ip[j + 1])
        h.update(struct.pack("<I", b - a))
        h.update(ids[a:b].tobytes())
        h.update(vals[a:b].tobytes())
    for lst in (rownames, colnames):
        h.update(struct.pack("<I", len(lst)))
        for s in lst:
            h.update(s.encode("utf-8") + b"\0")
    for k in sorted(kv, key=lambda s: s.encode("utf-8")):
        h.update(k.encode("utf-8") + b"\0" + str(kv[k]).encode("utf-8") + b"\0")
    return h.digest()[:16]


# ----------------------------------------------------------------------------------------------------------- helpers
def _rev(keys, study_files) -> str:
    h = hashlib.sha256(b"SGMREV1\n")
    for k in sorted(keys):
        h.update(k.encode() + b"\n")
    for name in sorted(study_files):
        h.update(name.encode() + b"\0" + study_files[name]["sha256"].encode() + b"\n")
    return h.hexdigest()[:16]


def _called_from_calls(data: bytes):
    """Barcodes called in a legacy cell_calls.tsv by the rule of ``SingletBundle`` (csv module based)."""
    txt = data.decode("utf-8", "replace")
    if not txt.strip():
        return None
    rd = csv.reader(io.StringIO(txt, newline=""), delimiter="\t")
    rows = list(rd)
    head = rows[0]
    col = None
    for c in ("barcode", "cb", "cell_barcode", "CB"):
        if c in head:
            col = head.index(c)
            break
    if col is None:
        return None
    ic = head.index("is_cell") if "is_cell" in head else None
    out = []
    for r in rows[1:]:
        if not r or col >= len(r) or not r[col]:
            continue
        if ic is not None and (
            ic >= len(r) or r[ic].strip().lower() not in ("true", "t", "1", "1.0", "yes", "y")
        ):
            continue
        out.append(r[col])
    return out


def _col_sums(indptr, data, n):
    ip = np.asarray(indptr).astype(np.int64)
    d = np.asarray(data).astype(np.uint64)
    out = np.zeros(n, dtype=np.uint64)
    for j in range(n):
        out[j] = d[ip[j] : ip[j + 1]].sum(dtype=np.uint64)
    return out


# ----------------------------------------------------------------------------------------------------------- main check
def verify(
    bundle_src: str,
    store_dir: str,
    gse: Optional[str] = None,
    samples: Optional[list] = None,
    recipes_spec=None,
    log=print,
    quick: bool = False,
) -> Report:
    from .context import StudyContext, StoreContext
    from .packs import PackStore, pack_id
    from .rcp_adapter import load_recipes
    from .sample import StoreSample

    rep = Report()
    t0 = time.time()
    leg = open_legacy(bundle_src)
    lnames = leg.names()
    root = os.path.join(store_dir, "store")
    if not os.path.isdir(root) and os.path.isdir(os.path.join(store_dir, "v2")):  # DUAL: an output tree under the old v2/ prefix
        root = os.path.join(store_dir, "v2")
    study_leg = {n: leg.read(n) for n in lnames if not n.startswith("samples/")}
    if not gse and "manifest.json" in study_leg:
        gse = json.loads(study_leg["manifest.json"]).get("gse_id")
    if not gse:
        mans = [f for f in os.listdir(os.path.join(root, "m")) if f.endswith(".json")]
        if len(mans) != 1:
            raise SystemExit("cannot tell the study: pass --gse")
        gse = mans[0][:-5]
    mpath = os.path.join(root, "m", gse + ".json")
    rep.check(os.path.exists(mpath), "manifest", "%s missing" % mpath)
    man = json.load(open(mpath, encoding="utf-8"))
    rep.check(man.get("format") in ("singlet-store", "singlet-v2") and man.get("gse") == gse, "manifest", "format/gse")
    rep.check(
        man.get("rev") == _rev([s["key"] for s in man["samples"]], man["study_files"]),
        "manifest",
        "rev does not match the sample keys + study files",
    )

    # ---- packs: the ones shipped next to the objects
    ref_dir = os.path.join(root, "ref")
    store = PackStore(dirs=[ref_dir], download=False)
    idx_path = os.path.join(ref_dir, "index.json")
    if os.path.exists(idx_path):
        for e in json.load(open(idx_path))["packs"]:
            fp = os.path.join(ref_dir, e["id"] + ".pack")
            d = open(fp, "rb").read() if os.path.exists(fp) else b""
            rep.check(
                bool(d)
                and hashlib.sha256(d).hexdigest() == e["sha256"]
                and pack_id(d).hex() == e["id"]
                and len(d) == e["bytes"],
                "pack " + e["id"],
                "pack file does not match index.json",
                "packs",
            )
    recipes = load_recipes(recipes_spec)

    # ---- study files
    for name, ent in man["study_files"].items():
        where = "study:" + name
        if not rep.check(name in study_leg, where, "not in the legacy bundle"):
            continue
        want = study_leg[name]
        size, crc = leg.info(name)
        rep.check(
            ent["size"] == len(want) == size
            and ent["crc32"] == crc == (zlib.crc32(want) & 0xFFFFFFFF)
            and ent["sha256"] == hashlib.sha256(want).hexdigest(),
            where,
            "size/crc/sha256 in the manifest",
            "study files",
        )
        try:
            if "recipe" in ent:
                got = bytes(
                    recipes.regenerate_bytes(
                        ent["recipe"],
                        ent.get("params", {}),
                        StudyContext(gse, man.get("reference_build", ""), {}, store),
                    )
                )
            elif "json" in ent:
                kw = dict(ent["dumps"])
                if "separators" in kw:
                    kw["separators"] = tuple(kw["separators"])
                got = json.dumps(ent["json"], **kw).encode("utf-8")
            else:
                import base64

                got = zstandard.ZstdDecompressor().decompress(
                    base64.b64decode(ent["zstd_b64"]), max_output_size=len(want) + 1
                )
        except Exception as ex:
            got = None
            rep.check(False, where, "regeneration failed: %s: %s" % (type(ex).__name__, ex))
        if got is not None:
            rep.check(
                got == want, where, "regenerated bytes differ from the legacy file", "study files"
            )
    for n in study_leg:
        rep.check(
            n in man["study_files"], "study:" + n, "legacy study file missing from the manifest"
        )

    # ---- samples
    lsamples = []
    for n in lnames:
        if n.startswith("samples/"):
            g = n.split("/", 2)[1]
            if g not in lsamples:
                lsamples.append(g)
    want_samples = [g for g in lsamples if samples is None or g in samples]
    by_gsm = {s["gsm"]: s for s in man["samples"]}
    for g in want_samples:
        rep.check(g in by_gsm, g, "sample missing from the manifest")
    if samples is None:
        for g in by_gsm:
            rep.check(g in lsamples, g, "manifest lists a sample the legacy bundle does not have")
    for role, pid in (man.get("packs") or {}).items():
        for p in [pid] if isinstance(pid, str) else (pid or []):
            rep.check(
                os.path.exists(os.path.join(ref_dir, p + ".pack")),
                "manifest packs." + role,
                "pack %s is not in store/ref" % p,
                "packs",
            )
    totals = {"legacy": 0, "store": 0}
    for g in want_samples:
        if g not in by_gsm:
            continue
        ent = by_gsm[g]
        opath = os.path.join(store_dir, ent["key"])
        if not rep.check(os.path.exists(opath), g, "object %s missing" % ent["key"]):
            continue
        obj = open(opath, "rb").read()
        totals["store"] += len(obj)
        rep.check(
            len(obj) == ent["bytes"] and hashlib.sha256(obj).hexdigest() == ent["sha256"],
            g,
            "object size/sha256 differ from the manifest",
            "objects",
        )
        rep.check(
            os.path.basename(ent["key"]) in tuple(hashlib.sha256(obj).digest()[:16].hex() + x for x in (".s1", ".s2")),
            g,
            "object name is not its digest16",
            "objects",
        )
        try:
            tab = parse_s2(obj)
        except Exception as ex:
            rep.check(False, g, "cannot parse the object table: %s" % ex)
            continue
        rep.check(tab["sample_id"] == g, g, "sample id in the header")
        members = tab["members"]
        # manifest member table agrees with the object
        for mn, mm in ent["members"].items():
            t = members.get(mn)
            rep.check(
                t is not None
                and t["kind"] == mm["kind"]
                and t["off"] == mm["off"]
                and t["len"] == mm["len"]
                and t["digest"].hex() == mm["digest"],
                "%s/%s" % (g, mn),
                "manifest member entry != object table",
                "manifest members",
            )
        try:
            sample = StoreSample(obj, store)
            ctx = StoreContext(sample, recipes, gse, man.get("reference_build", ""), {}, "")
        except Exception as ex:
            rep.check(False, g, "cannot open the object: %s: %s" % (type(ex).__name__, ex))
            continue
        sp = {
            rel: full
            for rel, full in (
                (n[len("samples/%s/" % g) :], n) for n in lnames if n.startswith("samples/%s/" % g)
            )
        }
        mats: dict = {}
        # ---- every legacy member
        for rel, full in sp.items():
            where = "%s/%s" % (g, rel)
            try:
                where = "%s/%s" % (g, rel)
                want = leg.read(full)
                size, crc = leg.info(full)
                totals["legacy"] += size
                rep.check(
                    len(want) == size and (zlib.crc32(want) & 0xFFFFFFFF) == crc,
                    where,
                    "legacy member fails its own ZIP CRC/size",
                )
                t = members.get(rel)
                if not rep.check(t is not None, where, "no store counterpart"):
                    continue
                rep.check(bool(t["flags"] & 1), where, "legacy flag not set")
                k = t["kind"]
                if k == 1:
                    try:
                        L = read_1pz(want)
                    except Exception as ex:
                        rep.check(False, where, "legacy matrix unreadable: %s" % ex)
                        continue
                    V = sample.matrix(rel)
                    mats[rel] = (L, V)
                    rep.container["not_applicable"] += (
                        1  # a pz2 member does not keep the legacy container bytes
                    )
                    ok = True
                    ok &= rep.check(
                        (L["m"], L["n"]) == (V.m, V.n),
                        where,
                        "shape %s vs %s" % ((L["m"], L["n"]), (V.m, V.n)),
                        "matrices",
                    )
                    ok &= rep.check(
                        np.array_equal(np.asarray(L["indptr"], np.int64), V.indptr),
                        where,
                        "indptr",
                        "matrices",
                    )
                    ok &= rep.check(
                        np.array_equal(
                            np.asarray(L["indices"], np.int64), V.indices.astype(np.int64)
                        ),
                        where,
                        "indices",
                        "matrices",
                    )
                    ok &= rep.check(
                        np.array_equal(np.asarray(L["data"], np.int64), V.data.astype(np.int64)),
                        where,
                        "data",
                        "matrices",
                    )
                    ok &= rep.check(
                        list(L["rownames"]) == list(V.rownames), where, "row names", "matrices"
                    )
                    ok &= rep.check(
                        list(L["colnames"]) == list(V.colnames), where, "column names", "matrices"
                    )
                    ok &= rep.check(
                        dict(L["user_kv"]) == dict(V.kv), where, "key/values", "matrices"
                    )
                    if not quick:
                        d = slow_digest(
                            L["m"],
                            L["n"],
                            L["indptr"],
                            L["indices"],
                            L["data"],
                            int(L["vt_code"]),
                            list(L["rownames"]),
                            list(L["colnames"]),
                            dict(L["user_kv"]),
                        )
                        rep.check(
                            d == t["digest"] and d == V.meta["digest"],
                            where,
                            "canonical digest (independent) %s != table %s / header %s"
                            % (d.hex(), t["digest"].hex(), V.meta["digest"].hex()),
                            "digests",
                        )
                elif k in (3, 5):
                    body = obj[t["off"] : t["off"] + t["len"]]
                    got = (
                        zstandard.ZstdDecompressor().decompress(
                            body, max_output_size=t["out_len"] + 1
                        )
                        if k == 3
                        else body
                    )
                    rep.check(
                        got == want
                        and len(got) == t["out_len"]
                        and (zlib.crc32(got) & 0xFFFFFFFF) == t["crc"] == crc,
                        where,
                        "stored bytes differ from the legacy member",
                        "stored",
                    )
                    if rel.endswith(".1pz"):
                        rep.container["equal"] += (
                            1  # stored verbatim: the matrix is equal because the bytes are
                        )
                    rep.check(
                        hashlib.sha256(want).digest()[:16] == t["digest"],
                        where,
                        "digest of the stored member",
                        "stored",
                    )
                elif k == 4:
                    meta = t["meta"]
                    try:
                        if rel.endswith(".1pz"):
                            out = ctx.regenerate_matrix(rel)
                            L = read_1pz(want)
                            from .context import rmatrix_to_csc

                            V = rmatrix_to_csc(out, int(L["vt_code"]))
                            ok = (
                                (V.m, V.n) == (L["m"], L["n"])
                                and np.array_equal(V.indptr, np.asarray(L["indptr"], np.int64))
                                and np.array_equal(
                                    V.indices.astype(np.int64), np.asarray(L["indices"], np.int64)
                                )
                                and np.array_equal(
                                    V.data.astype(np.int64), np.asarray(L["data"], np.int64)
                                )
                                and list(V.rownames or []) == list(L["rownames"])
                                and list(V.colnames or []) == list(L["colnames"])
                                and dict(V.kv) == dict(L["user_kv"])
                            )
                            rep.check(
                                ok,
                                where,
                                "derived matrix differs from the legacy matrix",
                                "derived",
                            )
                            if meta.get("bytes_exact"):
                                try:
                                    b = bytes(ctx.regenerate(rel))
                                    rep.container[
                                        "equal"
                                        if b == want and (zlib.crc32(b) & 0xFFFFFFFF) == t["crc"]
                                        else "differs"
                                    ] += 1
                                except Exception:  # the writer that reproduced the bytes at migration time is not available here
                                    rep.container["unavailable"] += 1
                            else:
                                rep.container["not_applicable"] += 1
                        else:
                            b = bytes(ctx.regenerate(rel))
                            rep.check(
                                b == want
                                and len(b) == t["out_len"] == size
                                and (zlib.crc32(b) & 0xFFFFFFFF) == t["crc"] == crc,
                                where,
                                "regenerated bytes differ from the legacy member (recipe %s)"
                                % meta.get("recipe"),
                                "derived",
                            )
                    except Exception as ex:
                        rep.check(
                            False,
                            where,
                            "regeneration failed (recipe %s): %s: %s"
                            % (meta.get("recipe"), type(ex).__name__, ex),
                        )
                else:
                    rep.check(False, where, "unexpected member kind %d for a legacy member" % k)
            except Exception as ex:  # a damaged object must be reported, not crash the verifier
                rep.check(
                    False, where, "exception while checking: %s: %s" % (type(ex).__name__, ex)
                )
        # members the legacy bundle does not have, flagged as legacy
        for mn, t in members.items():
            if t["flags"] & 1:
                rep.check(
                    mn in sp, "%s/%s" % (g, mn), "store legacy-flagged member not in the legacy bundle"
                )
        # ---- cells table
        try:
            if "cells" in members:
                cells = sample.cells()
                where = g + "/cells"
                rep.check(
                    cells.digest() == members["cells"]["digest"], where, "cells digest", "cells"
                )
                basis = None
                for cand in ("exon_counts.1pz", "intron_counts.1pz"):
                    if cand in mats and mats[cand][0]["n"] > 0:
                        basis = mats[cand][0]
                        break
                if basis is not None:
                    bc = list(basis["colnames"])
                    rep.check(
                        list(cells.barcodes) == bc,
                        where,
                        "barcodes != basis matrix columns",
                        "cells",
                    )
                    for tag in ("exon", "intron"):
                        key = "%s_counts.1pz" % tag
                        if (
                            key in mats
                            and mats[key][0]["n"] == len(bc)
                            and list(mats[key][0]["colnames"]) == bc
                        ):
                            Lm = mats[key][0]
                            rep.check(
                                np.array_equal(
                                    cells.column("n_umi_" + tag).astype(np.uint64),
                                    _col_sums(Lm["indptr"], Lm["data"], Lm["n"]),
                                ),
                                where,
                                "n_umi_" + tag,
                                "cells",
                            )
                            rep.check(
                                np.array_equal(
                                    cells.column("n_feat_" + tag).astype(np.int64),
                                    np.diff(np.asarray(Lm["indptr"], np.int64)),
                                ),
                                where,
                                "n_feat_" + tag,
                                "cells",
                            )
                        elif key not in mats or mats[key][0]["n"] == 0:
                            rep.check(
                                not cells.column("n_umi_" + tag).any()
                                and not cells.column("n_feat_" + tag).any(),
                                where,
                                tag + " columns should be 0",
                                "cells",
                            )
                    ccn = "samples/%s/cell_calls.tsv" % g
                    if ccn in lnames:
                        called = _called_from_calls(leg.read(ccn))
                        if called is not None:
                            cs = set(called)
                            rep.check(
                                [b in cs for b in bc] == cells.column("called").tolist(),
                                where,
                                "called flags",
                                "cells",
                            )
                        else:
                            rep.check(
                                bool(cells.column("called").all()),
                                where,
                                "no usable cell_calls: all cells should be called",
                                "cells",
                            )
                    else:
                        rep.check(
                            bool(cells.column("called").all()),
                            where,
                            "no cell_calls.tsv: all cells should be called",
                            "cells",
                        )
                rep.check(
                    ent["n_columns"] == cells.n_rows
                    and ent["n_called"] == int(cells.column("called").sum()),
                    where,
                    "manifest n_columns/n_called",
                    "cells",
                )
            else:
                rep.check(
                    not any(
                        mats[r][0]["n"] > 0
                        for r in ("exon_counts.1pz", "intron_counts.1pz")
                        if r in mats
                    ),
                    g,
                    "matrices with columns but no cells table",
                    "cells",
                )
        except Exception as ex:
            rep.check(
                False, g + "/cells", "exception while checking: %s: %s" % (type(ex).__name__, ex)
            )
    log("verify %s: %d checks passed, %d failed, %.1fs" % (gse, rep.ok, rep.fail, time.time() - t0))
    log(
        "  samples %d, legacy member bytes %d, store object bytes %d"
        % (len(want_samples), totals["legacy"], totals["store"])
    )
    for k, (a, b) in sorted(rep.by_kind.items()):
        log("  %-18s %6d ok %4d failed" % (k, a, b))
    log(
        "  .1pz container bytes (informational, not a pass criterion): "
        + ", ".join("%s %d" % kv for kv in rep.container.items())
    )
    rep.totals = totals
    return rep


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        prog="python -m singlet.store.verify",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument("--bundle", required=True)
    ap.add_argument("--store", required=True, help="output directory of singlet.store.migrate")
    ap.add_argument("--gse")
    ap.add_argument("--samples")
    ap.add_argument("--recipes")
    ap.add_argument(
        "--quick", action="store_true", help="skip the slow independent digest recomputation"
    )
    a = ap.parse_args(argv)
    rep = verify(
        a.bundle, a.store, a.gse, a.samples.split(",") if a.samples else None, a.recipes, quick=a.quick
    )
    return 1 if rep.fail else 0


if __name__ == "__main__":
    sys.exit(main())
